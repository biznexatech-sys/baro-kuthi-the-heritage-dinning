// Copies the design system's CSS and fonts into the site, so ../design-system stays the single source of truth.
//   design-system/styles.css (+ every file it @imports) → src/styles/ds/   (same relative paths)
//   design-system/fonts/*.woff2                           → public/fonts/
// Runs automatically before `npm run dev` and `npm run build`. Never edit the copies — edit design-system/.
//
// Files are written in place and only when their content changed; only stale files are removed. Never delete and
// recreate the folders: a running `next dev` (Turbopack) caches "file missing" if it sees them vanish, and keeps
// failing with "Can't resolve '../styles/ds/index.css'" until .next/ is cleared.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync, existsSync, rmSync, statSync } from 'node:fs';
import { dirname, join, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ds = resolve(site, '..', 'design-system');
const outCss = join(site, 'src', 'styles', 'ds');
const outFonts = join(site, 'public', 'fonts');
const banner = '/* GENERATED by scripts/sync-design-system.mjs from design-system/ — do not edit. */\n';

if (!existsSync(join(ds, 'styles.css'))) {
  console.error(`sync-design-system: ${join(ds, 'styles.css')} not found. The site expects the design system at ../design-system.`);
  process.exit(1);
}

let changed = 0;
const written = new Set();

function writeIfChanged(target, content) {
  written.add(target);
  if (existsSync(target) && readFileSync(target, 'utf8') === content) return;
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
  changed++;
}

function copyIfChanged(from, target) {
  written.add(target);
  if (existsSync(target) && statSync(target).size === statSync(from).size && readFileSync(target).equals(readFileSync(from))) return;
  mkdirSync(dirname(target), { recursive: true });
  copyFileSync(from, target);
  changed++;
}

function removeStale(dir) {
  if (!existsSync(dir)) return;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) {
      removeStale(p);
      if (readdirSync(p).length === 0) rmSync(p, { recursive: true });
    } else if (!written.has(p)) {
      rmSync(p);
      changed++;
    }
  }
}

const entry = readFileSync(join(ds, 'styles.css'), 'utf8');
const imports = [...entry.matchAll(/@import\s+url\(['"]?([^'")]+)['"]?\)\s*;/g)].map((m) => m[1]);

for (const rel of imports) {
  // Fonts are served from public/fonts, so point @font-face at the site root.
  const css = readFileSync(join(ds, rel), 'utf8').replace(/url\((['"]?)(?:\.\.\/)+fonts\//g, 'url($1/fonts/');
  writeIfChanged(join(outCss, rel), banner + css);
}
writeIfChanged(join(outCss, 'index.css'), banner + imports.map((rel) => `@import './${rel}';`).join('\n') + '\n');

const fonts = readdirSync(join(ds, 'fonts')).filter((f) => f.endsWith('.woff2'));
for (const f of fonts) copyIfChanged(join(ds, 'fonts', f), join(outFonts, f));

removeStale(outCss);
removeStale(outFonts);

console.log(`sync-design-system: ${imports.length} stylesheets, ${fonts.length} fonts — ${changed ? changed + ' file(s) updated' : 'up to date'} (${relative(site, outCss)}, ${relative(site, outFonts)})`);
